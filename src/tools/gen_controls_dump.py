#!/usr/bin/env python3
"""Generate io/test/controls_dump.inc: one write per element of every
star%ctrl and star%job member, for test_controls.

Source: state/controls_state_def.inc and state/job_controls_def.inc
(generated by tools/gen_controls_state.py from io/controls_buffer.f90).
Regenerate after either changes:  python3 tools/gen_controls_dump.py
Each line written is `ctrl%name(i,j) = value`, with doubles at full
precision (es25.17e3), so two dumps are equal exactly when the values
are bit-identical.
"""
import pathlib
import re

SRC = pathlib.Path(__file__).resolve().parent.parent
DEFS = [("ctrl", SRC / "state" / "controls_state_def.inc"),
        ("job", SRC / "state" / "job_controls_def.inc")]
OUT = SRC / "io" / "test" / "controls_dump.inc"

DECL = re.compile(r"^\s*(double precision|integer|logical|character\(len=\d+\))\s*::\s*(\w+)\s*(\(([^)]*)\))?")
FMT = {"double precision": "es25.17e3", "integer": "i0", "logical": "l1"}


def dims_of(spec):
    if not spec:
        return []
    return [d.strip() for d in spec.split(",")]


def emit(group, name, kind, dims):
    ref = f"star%{group}%{name}"
    if kind.startswith("character"):
        fmt, val = "a", f"'\"'//trim({ref}{{idx}})//'\"'"
    else:
        fmt, val = FMT[kind], f"{ref}{{idx}}"
    label = f"{group}%{name}"
    if not dims:
        return [f"      write(u,'(a,\" = \",{fmt})') '{label}', {val.format(idx='')}"]
    loops = []
    idx_vars = ["i1", "i2", "i3"][:len(dims)]
    lines = []
    for v, d in reversed(list(zip(idx_vars, dims))):
        pass
    # nested loops, first index fastest
    for v, d in zip(reversed(idx_vars), reversed(dims)):
        lines.append(f"      do {v} = 1, {d}")
    idx = "(" + ",".join(idx_vars) + ")"
    lab = "'" + label + "('" + "".join(f"//itoa({v})" + ("//','" if k < len(idx_vars) - 1 else "") for k, v in enumerate(idx_vars)) + "//')'"
    lines.append(f"      write(u,'(a,\" = \",{fmt})') {lab}, {val.format(idx=idx)}")
    lines += ["      end do"] * len(dims)
    return lines


out = ["! GENERATED by tools/gen_controls_dump.py from state/controls_state_def.inc",
       "! and state/job_controls_def.inc -- do not edit; regenerate instead.",
       "! One write per element of every star%ctrl and star%job member."]
n = 0
for group, path in DEFS:
    for line in path.read_text().splitlines():
        m = DECL.match(line)
        if not m:
            continue
        kind, name, dims = m.group(1), m.group(2), dims_of(m.group(4))
        out += emit(group, name, kind, dims)
        n += 1
OUT.write_text("\n".join(out) + "\n")
print(f"{n} members -> {OUT.relative_to(SRC)}")
