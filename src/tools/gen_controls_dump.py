#!/usr/bin/env python3
"""Generate io/test/controls_dump.inc: one write per element of every
star%control and star%physics member, of every controls_buffer member the
star does not hold (registry home buffer, printed as buffer%<name>), and
of every run copy, for test_controls.

Source: controls_buffer.f90's declarations (controls_registry's
buffer_members, the parser gen_controls_state and gen_inlist use) and the
registry's home and run_copy columns (gen_controls_state's homes), in
declaration order, the records' members first, as the records hold them.
make reruns it, with the other controls generators, when controls_buffer
or the registry changes (src/Makefile); by hand:
python3 tools/gen_controls_dump.py
Each line written is `control%name(i,j) = value` (or physics%...), with doubles at full
precision (es25.17e3), so two dumps are equal exactly when the values
are bit-identical.
"""
import pathlib

from generated_files import emit, finish
import controls_registry
import gen_controls_state

SRC = pathlib.Path(__file__).resolve().parent.parent
OUT = SRC / "io" / "test" / "controls_dump.inc"

FMT = {"real(dp)": "es25.17e3", "integer": "i0", "logical": "l1"}
# The deck's own file names: where the deck came from, not what it sets
# (test_controls names its decks by their paths, which differ from one
# checkout to the next).
NOT_DUMPED = {"control_nml_file", "physics_nml_file"}


SIZES = controls_registry.named_sizes()


def dims_of(spec):
    """the extents of a dims spec, a named size (max_runs) as its value"""
    if not spec:
        return []
    return [SIZES.get(d.strip().lower(), d.strip()) for d in spec.split(",")]


def writes_for(group, name, kind, dims):
    """the writes of one member: group control or physics (star%<group>%name),
    buffer (the buffer's name) or star (a run copy, star%name)"""
    ref = {"buffer": name, "star": f"star%{name}"}.get(group, f"star%{group}%{name}")
    if kind.startswith("character"):
        fmt, val = "a", f"'\"'//trim({ref}{{idx}})//'\"'"
    else:
        fmt, val = FMT[kind], f"{ref}{{idx}}"
    label = f"{group}%{name}"
    if not dims:
        return [f"      write(u,'(a,\" = \",{fmt})') '{label}', {val.format(idx='')}"]
    idx_vars = ["i1", "i2", "i3"][:len(dims)]
    lines = []
    # nested loops, first index fastest
    for v, d in zip(reversed(idx_vars), reversed(dims)):
        lines.append(f"      do {v} = 1, {d}")
    idx = "(" + ",".join(idx_vars) + ")"
    lab = "'" + label + "('" + "".join(f"//itoa({v})" + ("//','" if k < len(idx_vars) - 1 else "") for k, v in enumerate(idx_vars)) + "//')'"
    lines.append(f"      write(u,'(a,\" = \",{fmt})') {lab}, {val.format(idx=idx)}")
    lines += ["      end do"] * len(dims)
    return lines


body, buffer_names = [], []
n = 0
members = controls_registry.buffer_members()
home, _ = gen_controls_state.homes(members)
for group in ("control", "physics", "buffer"):
    for m in members:
        if home[m["name"]] != group or m["name"] in NOT_DUMPED:
            continue
        body += writes_for(group, m["spelled"], m["decl"], dims_of(m["dims"].strip("()")))
        if group == "buffer":
            buffer_names.append(m["spelled"])
        n += 1
# the run copies, star members of their controls' types (check_boundaries
# checks the declarations): what arm_run_copies set from the read
KIND = {"real": "real(dp)", "integer": "integer", "logical": "logical"}
for r in controls_registry.rows():
    if not r["run_copy"]:
        continue
    typ = controls_registry.declared_type(r["type"])
    base, _, dims = typ.partition("(")
    body += writes_for("star", r["run_copy"], KIND.get(base, "character"), dims_of(dims.rstrip(")")))
    n += 1
out = ["! GENERATED by tools/gen_controls_dump.py from state/control_group_def.inc,",
       "! state/physics_group_def.inc, io/controls_buffer.f90 and",
       "! defaults/controls_registry.tsv -- do not edit; regenerate instead.",
       "! test_controls' dump_controls: one write per element of every",
       "! star%control and star%physics member, of every buffer-only member, and",
       "! of every run copy (star%<run copy>, as arm_run_copies set it); itoa is",
       "! test_controls'."
       , "subroutine dump_controls(star, u)"]
line = "      use controls_buffer, only: "
for i, name in enumerate(buffer_names):
    piece = name + (", " if i < len(buffer_names) - 1 else "")
    if len(line) + len(piece) > 78:
        out.append(line.rstrip() + " &")
        line = "           "
    line += piece
out += [line.rstrip(),
        "      type(star_info), intent(in) :: star",
        "      integer, intent(in) :: u",
        "      integer :: i1, i2"]
out += body + ["end subroutine dump_controls"]
emit(OUT, "\n".join(out) + "\n")
finish("gen_controls_dump.py")
print(f"{n} members -> {OUT.relative_to(SRC)}")
