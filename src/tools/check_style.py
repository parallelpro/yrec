def production_files(src_root):
    """(directory, path relative to src/, Source) of every production
    .f90 file."""
    out = []
    for f in sorted(src_root.rglob("*.f90")):
        rel = f.relative_to(src_root).as_posix()
        if "/test/" in "/" + rel or rel.startswith("test/"):
            continue
        text = f.read_text(errors="replace")
        if any(GENERATED.search(l) for l in text.splitlines()[:10]):
            continue
        out.append((rel.rsplit("/", 1)[0] if "/" in rel else ".", rel, Source(text)))
    return out


def shared_character_names(files):
    shared = set()
    for _, _, src in files:
        shared |= character_names(src)[1]
    return shared


def occurrences(files):
    """{(directory, metric): [(file, line, text)]} over files."""
    occ = {}
    shared = shared_character_names(files)

    def add(d, metric, rel, line, src, n=1):
        for _ in range(n):
            occ.setdefault((d, metric), []).append((rel, line, src.lines[line - 1].strip()))

    for d, rel, src in files:
        for metric in METRICS:
            occ.setdefault((d, metric), [])
        for i, code in enumerate(src.code, 1):
            add(d, "double_precision", rel, i, src, len(DOUBLE_PRECISION.findall(code)))
            add(d, "old_relational", rel, i, src, len(OLD_RELATIONAL.findall(code)))
            add(d, "endif_enddo", rel, i, src, len(ENDIF_ENDDO.findall(code)))
            add(d, "specific_intrinsic", rel, i, src, len(SPECIFIC.findall(code)))
        code_lines = set(commented_code_lines(src))
        for i in sorted(code_lines):
            add(d, "commented_code", rel, i, src)
        for i, text in enumerate(src.comment, 1):
            if text is not None and i not in code_lines and is_caps(text):
                add(d, "caps_comment", rel, i, src)

        local_chars = set()

        def visit(stack, line, stmt):
            dcl = declaration(stmt)
            if dcl and dcl[0] == "character":
                local_chars.update(n for n, _ in dcl[2])
            if re.match(r"(?i)^use\b", stmt):
                m = re.match(r"(?i)^use\s*(?:,\s*(?:non_)?intrinsic\s*)?(?:::)?\s*(\w+)(.*)$", stmt)
                if m and m.group(1).lower() != "math_lib" and \
                        not re.match(r"(?i)\s*,\s*only\s*:", m.group(2)):
                    add(d, "use_no_only", rel, line, src)
                return
            proc = next((s for s in reversed(stack) if s.kind == "procedure"), None)
            if proc is None or stack[-1].kind != "procedure":
                return
            if dcl is None:
                mm = re.match(r"(?i)^dimension\b\s*(?:::)?\s*(.*)$", stmt)
                if not mm:
                    return
                ents = []
                for e in split_top(mm.group(1)):
                    em = re.match(r"(?i)\s*([a-z_]\w*)\s*\((.*)\)\s*$", e)
                    if em:
                        ents.append((em.group(1).lower(), em.group(2)))
            else:
                ents = dcl[2]
            for name, spec in ents:
                if name in proc.dummies and spec is not None and name not in proc.seen:
                    proc.seen.add(name)
                    if not assumed_shape(spec):
                        add(d, "explicit_shape_dummy", rel, line, src)

        modules = walk_scopes(src, visit)
        for name, line, private in modules:
            if not private:
                add(d, "module_no_private", rel, line, src)
        if not rel.endswith("_messages.f90"):
            for line, _ in io_statements(src, shared, local_chars):
                add(d, "io_statement", rel, line, src)
    return occ


def read_table(path=TABLE):
    table = {}
    if not path.exists():
        return None
    for n, line in enumerate(path.read_text().splitlines(), 1):
        if n == 1 or not line.strip() or line.startswith("#"):
            continue
        d, metric, allowed = line.split("\t")
        table[(d, metric)] = int(allowed)
    return table


def write_table(table, path=TABLE):
    rows = ["directory\tmetric\tallowed"]
    for (d, metric) in sorted(table, key=lambda k: (k[0], METRICS.index(k[1]))):
        rows.append(f"{d}\t{metric}\t{table[(d, metric)]}")
    path.write_text("\n".join(rows) + "\n")


def report(counts, dirs):
    short = ["dprec", "oldrel", "endif", "spec", "caps", "ccode", "nopriv", "noonly",
             "explic", "io"]
    print("%-22s" % "directory" + "".join("%8s" % s for s in short))
    totals = {}
    for d in dirs:
        row = [counts[(d, m)] for m in METRICS]
        top = d.split("/")[0]
        totals[top] = [a + b for a, b in zip(totals.get(top, [0] * len(METRICS)), row)]
        print("%-22s" % d + "".join("%8d" % v for v in row))
    print()
    print("%-22s" % "package (tree)" + "".join("%8s" % s for s in short))
    for top in sorted(totals):
        print("%-22s" % top + "".join("%8d" % v for v in totals[top]))
    print()
    print("columns: " + ", ".join(f"{s} = {m}" for s, m in zip(short, METRICS)))


def self_test():
    cases = 0

    def expect(cond, what):
        nonlocal cases
        cases += 1
        if not cond:
            raise SystemExit(f"check_style self-test failed: {what}")

    src = Source("""module m
   use iso_fortran_env
   use math_lib
   use foo, only: bar
   use, intrinsic :: ieee_arithmetic
   character(len=80) :: shared_line
   type t
      private
      double precision :: x(3)
   end type t
contains
   subroutine s(a, b, c, n, msg, d)
      integer, intent(in) :: n
      double precision, intent(in) :: a(n), b(:), c(0:)
      double precision, dimension(n,*) :: d
      character(len=*) :: msg
      character(len=20) :: buf
      write(buf, '(i3)') n
      write(msg, *) n
      write(*,*) 'x'
      if (n.gt.0) write(6, 10) n
      read(buf, *) i
      print *, 'it''s ! not a comment'
      if (n > 0) call report_error('a')
   endif
   end subroutine s
end module m
module p
   public
end module p
""")
    occ = occurrences([(".", "m.f90", src)])
    n = {k[1]: len(v) for k, v in occ.items()}
    expect(n["use_no_only"] == 2, f"use_no_only {n['use_no_only']} (iso_fortran_env, ieee)")
    expect(n["module_no_private"] == 2, "module m (private only in a type) and p")
    expect(n["explicit_shape_dummy"] == 2, f"explicit_shape_dummy {n['explicit_shape_dummy']} (a(n), d(n,*))")
    expect(n["io_statement"] == 3, f"io_statement {n['io_statement']} (write *, write 6, print)")
    expect(n["double_precision"] == 3, "double precision x3")
    expect(n["old_relational"] == 1, ".gt.")
    expect(n["endif_enddo"] == 1, "endif")
    for text, code in [
        ("call foo(a, b)", True), ("CALL EQUATION OF STATE TO GET THE DENSITY", False),
        ("x = a*b + c", True), ("tau = H_p/v_c.", False), ("g = G M / R^2.", False),
        ("radius_mid(i) = (radius(i) + radius(i-1))/2, the interface", False),
        ("if (x .gt. 0.0d0) then", True), ("if (the zone is convective) then", False),
        ("end if", True), ("do i = 1, n", True), ("write(*,*) 'x', y", True),
        ("delta = star%omega(i) - star%omega(i-1)", True), ("Bmag = Pphot**0.5 (w R**c)**b", False),
        ("cvt=(eos(5)*molenak/tmass+4.*er/t6)", True), ("chi(1) = 1,", False),
        ("ierr = 1 with a message in the run log.", False), ("x = f(a, &", True),
    ]:
        expect(statement_ok(text) == code, f"statement_ok({text!r}) should be {code}")
    for text, caps in [(" COMPUTE PRESSURE SCALE HEIGHT  H_P = P R^2/(G M rho).", True),
                       (" radius_bl - VECTOR OF UNLOGGED RADII IN BAHCALL AND LOEB UNITS.", True),
                       (" SPACED GRID.", True), (" OPAL", False), (" the OPAL EOS tables", False),
                       (" 50, MIDMOD and WRTOUT 43, HPOINT 35, GETW 29, MIX 21). The COMMON", False)]:
        expect(is_caps(text) == caps, f"is_caps({text!r}) should be {caps}")
    print(f"check_style self-test OK ({cases} cases)")
    return 0


def main():
    ap = argparse.ArgumentParser(description="style ratchet (see the module docstring)")
    ap.add_argument("--report", action="store_true", help="print the counts per directory")
    ap.add_argument("--list", metavar="METRIC", help="print a metric's occurrences")
    ap.add_argument("--dir", default="", help="with --list: a directory or a tree (e.g. core)")
    ap.add_argument("--update", action="store_true", help="lower the allowed values to today's counts")
    ap.add_argument("--init", action="store_true", help="write a new table from today's counts")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        return self_test()
    files = production_files(SRC)
    occ = occurrences(files)
    counts = {k: len(v) for k, v in occ.items()}
    dirs = sorted({d for d, _ in counts})
    if a.report:
        report(counts, dirs)
        return 0
    if a.list:
        if a.list not in METRICS:
            raise SystemExit(f"unknown metric {a.list}; one of {', '.join(METRICS)}")
        for (d, metric), hits in sorted(occ.items()):
            if metric == a.list and (not a.dir or d == a.dir or d.startswith(a.dir.rstrip("/") + "/")):
                for rel, line, text in hits:
                    print(f"{rel}:{line}: {text}")
        return 0
    if a.init:
        if TABLE.exists():
            raise SystemExit(f"{TABLE.name} exists; --update lowers it, a raise is a hand edit")
        write_table(counts)
        print(f"wrote {TABLE.relative_to(SRC.parent)} ({len(counts)} rows)")
        return 0
    table = read_table()
    if table is None:
        raise SystemExit(f"no {TABLE.name}; --init writes one from today's counts")
    over = [(k, counts[k], table.get(k, 0)) for k in sorted(counts) if counts[k] > table.get(k, 0)]
    if a.update:
        lowered = {k: min(v, counts.get(k, 0)) for k, v in table.items() if k[0] in dirs}
        for k in counts:
            lowered.setdefault(k, 0)
        changed = sum(1 for k in lowered if lowered[k] != table.get(k))
        write_table(lowered)
        print(f"{TABLE.name}: {changed} row(s) lowered or added at 0; none raised")
        if over:
            print("still above the table (a raise is a hand edit with a reason):")
            for (d, metric), n, allowed in over:
                print(f"  {d} {metric}: {n} > {allowed}")
            return 1
        return 0
    if over:
        print("STYLE RATCHET: counts above src/tools/style_counts.tsv")
        for (d, metric), n, allowed in over:
            print(f"{d} {metric}: {n} > allowed {allowed}")
            for rel, line, text in occ[(d, metric)]:
                print(f"  {rel}:{line}: {text[:100]}")
        print("Fix the new occurrences; a deliberate raise is a hand edit of the table, "
              "in a commit that says why.")
        return 1
    lower = sum(1 for k, v in table.items() if counts.get(k, 0) < v)
    print(f"Style ratchet OK: {len(counts)} counts at or below the table"
          + (f" ({lower} below: --update lowers them)" if lower else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
