#!/usr/bin/env python3
"""Style ratchet for the Fortran of src/ (docs/GUIDELINES.md, "Declarations
and interfaces" and "Code style").

    python3 src/tools/check_style.py                  check (exit 1 on a rise)
    python3 src/tools/check_style.py --report         print the counts
    python3 src/tools/check_style.py --list METRIC [--dir DIR]
                                                      print the occurrences
    python3 src/tools/check_style.py --update         lower the table to today
    python3 src/tools/check_style.py --self-test      the scanner's own cases

It counts ten metrics in each directory of src/ that holds production .f90
files, and compares each count with its allowed value in
src/tools/style_counts.tsv (directory, metric, allowed). A pair missing from
the table is allowed 0, so a new directory starts clean. The check fails
when a count is above its allowed value, and lists that metric's
occurrences in that directory. `--update` lowers each allowed value to
today's count and never raises one; a raise is a hand edit of the table,
in a commit that says why. test_boundaries.py runs the check.

Scope. A directory is a file's own directory (core/step and core are two
directories), not its tree. Production code only: files under a test/
directory are left out, and so are generated files (a "GENERATED by
tools/" line among the first ten). Only .f90 files are read; the .inc
files of src/ are all generated.

Reading the source. Each line is split into code and comment at the first
`!` outside a character literal (a literal continued with `&` carries its
quote to the next line). The code has the contents of its literals
blanked, so text inside quotes never counts. Lines starting with `#` are
preprocessor lines and are skipped. A statement is the code of a line and
its `&` continuation lines (comment lines between them skipped), split at
`;` and stripped of a leading statement label. A full-line comment is a
line with no code; its text is what follows the `!`s.

The metrics, exactly:

  double_precision      Occurrences of `double precision` (any case, any
                        spaces between the words) in code. Each one becomes
                        `real(dp)`.
  old_relational        Occurrences of `.eq.`, `.ne.`, `.lt.`, `.le.`,
                        `.gt.`, `.ge.` in code (`.eqv.`/`.neqv.` have no
                        symbolic form and do not count).
  endif_enddo           Occurrences of the words `endif` and `enddo` in code
                        (`end if`, `end do` are the style).
  specific_intrinsic    Calls of the specific names of generic intrinsics:
                        dabs dsqrt dexp dlog dlog10 dsin dcos dtan dasin
                        dacos datan datan2 dsinh dcosh dtanh dmax1 dmin1
                        amax1 amin1 amax0 amin0 max0 min0 max1 min1 dmod
                        dsign ddim dint dnint idint idnint iabs isign idim
                        alog alog10 float dfloat sngl ifix: the name, not
                        after `%` or a word character, followed by `(`.
                        (dble is a generic intrinsic and does not count.)
  caps_comment          Comment lines (full-line, or the comment after
                        code) whose text holds at least two words and eight
                        letters in its words, where a word is a run of two
                        or more letters, and at least 80% of the words are
                        upper case. A line counted as commented_code does
                        not count here.
  commented_code        Full-line comments whose text, less a trailing
                        `! ...` of its own, reads as a Fortran statement:
                        `call name(...)` or `call name`; `if (...) then`
                        or `if (...)` followed by such a statement; `else`,
                        `else if (...) then`; `end if`/`endif`, `end
                        do`/`enddo`, `end select`, `end subroutine`, `end
                        function`; `do i = a, b[, c]`, `do while (...)`;
                        `return`, `continue`, `cycle`, `exit`, `stop`,
                        `go to N`; `write (...) list`, `read (...) list`,
                        `print fmt, list`, `open/close/inquire (...)`,
                        `N format (...)`; `use name[, only: ...]`; a type
                        declaration with `::`; or an assignment `lhs = rhs`,
                        where lhs is a variable (with subscripts and `%`
                        components) and rhs one expression. An expression
                        has only Fortran tokens (names, numbers such as
                        1.5d-3, literals, operators, `.and.`-style
                        operators, parentheses), balanced parentheses, no
                        `,` or `:` or `=` outside parentheses, does not end
                        in an operator, and never has two operands side by
                        side (`G M`, `(a) (b)`: mathematics in prose, not
                        code). A statement may end in `&`, which allows
                        open parentheses; the line after such a code line
                        counts too when it is an expression fragment by the
                        same rules (parentheses may be unbalanced).
  module_no_private     Modules (not submodules) whose specification part
                        has no bare `private` statement (a `private` inside
                        a type definition does not count).
  use_no_only           `use` statements, intrinsic modules included,
                        without an `only:` list. `use math_lib` does not
                        count: under USE_CRMATH its procedures shadow the
                        intrinsics, which an only: list cannot express
                        (GUIDELINES, "Declarations and interfaces", rule 2).
  explicit_shape_dummy  Dummy arguments declared as arrays with any bound
                        other than an assumed-shape `:` or `lb:`: explicit
                        shape (`x(n)`, `xa(15,json)`, `y(0:n)`) and assumed
                        size (`a(*)`, `a(n,*)`), from the entity or a
                        `dimension(...)` attribute. Each dummy counts once
                        per procedure, interface bodies included.
  io_statement          I/O statements in files whose name does not end in
                        `_messages.f90`: write, read, print, open, close,
                        inquire, rewind, backspace, endfile, flush and wait,
                        at the start of a statement or after a logical
                        `if (...)`. A write or read whose unit is a
                        character variable (an internal file) is not I/O:
                        the unit's name (the last component of an `a%b`
                        designator) is declared `character` in the same
                        file, or at module level or as a type component in
                        any production file. io/ is the I/O layer, so its
                        counts are its job; elsewhere a message goes
                        through the domain's messages module.

The two comment metrics are heuristics. Checked by hand on 2026-11-10:
caps_comment, 0 false of a random 30 of its 517 lines; commented_code, 5
false of a random 30 of its 147 lines, and 8 false of all 147: a formula
or a contract written as an assignment (`! He4 = 1 - X - Z - He3`,
`! charge(num_species)=-1.`). Writing such a line as prose clears it.
"""
