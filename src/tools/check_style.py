WORD = re.compile(r"[A-Za-z]{2,}")


def is_caps(text):
    words = WORD.findall(text)
    if len(words) < 2 or sum(len(w) for w in words) < 8:
        return False
    return sum(w.isupper() for w in words) >= 0.8 * len(words)


TOKEN = re.compile(r"""\s*(?:
    (?P<str>'(?:[^']|'')*'|"(?:[^"]|"")*")
  | (?P<num>(?:\d+(?:\.(?!(?:and|or|not|eqv|neqv|eq|ne|lt|le|gt|ge|true|false)\.)\d*)?|\.\d+)
           (?:[edq][+-]?\d+)?(?:_\w+)?)
  | (?P<dot>\.(?:and|or|not|eqv|neqv|eq|ne|lt|le|gt|ge)\.)
  | (?P<lit>\.(?:true|false)\.(?:_\w+)?)
  | (?P<name>[a-z_]\w*)
  | (?P<op>\*\*|//|==|/=|<=|>=|=>|\(/|/\)|[-+*/<>=%,:()&\[\]])
)""", re.I | re.X)


class Tok(tuple):
    """A token (kind, value) that also knows whether blanks precede it."""
    space = False


def tokens(text):
    """Fortran tokens of text, or None if it holds anything else."""
    out, i, text = [], 0, text.rstrip()
    while i < len(text):
        m = TOKEN.match(text, i)
        if not m or m.end() == i:
            return None
        kind = m.lastgroup
        t = Tok((kind, m.group(kind)))
        t.space = m.start(kind) > i
        out.append(t)
        i = m.end()
    return out


OPERAND_END = {"str", "num", "lit", "name"}


def expression_ok(toks, fragment=False):
    """One Fortran expression (a fragment: parentheses may be open or
    closed from elsewhere, and it may end in `&`)."""
    if not toks:
        return False
    if toks[-1] == ("op", "&"):
        toks, fragment = toks[:-1], True
        if not toks:
            return True
    depth, prev = 0, None
    for tok in toks:
        kind, val = tok
        if kind == "op" and val in "([" or val == "(/":
            if prev and (prev[0] in ("str", "num", "lit") or prev[1] in (")", "]", "/)")):
                return False
            if prev and prev[0] == "name" and (val != "(" or tok.space):
                return False   # `G (M/R)`, `e_acc [1 + x]`: prose, not a call
            depth += 1
        elif kind == "op" and val in ")]" or val == "/)":
            depth -= 1
            if depth < 0 and not fragment:
                return False
        elif kind in OPERAND_END or (kind == "dot" and val.lower() == ".not."):
            if prev and (prev[0] in OPERAND_END or prev[1] in (")", "]", "/)")):
                return False
        elif kind == "op" and val in (",", ":", "=") and depth <= 0 and not fragment:
            return False
        elif kind == "op" and val == "&":
            return False
        prev = tok
    if depth != 0 and not fragment:
        return False
    last = toks[-1]
    if last[0] in ("op", "dot") and last[1] not in (")", "]", "/)") and not fragment:
        return False
    return True


def designator_end(toks):
    """Number of tokens of a variable designator at the start of toks
    (name, subscripts, % components), or 0."""
    i = 0
    while True:
        if i >= len(toks) or toks[i][0] != "name":
            return 0
        i += 1
        while i < len(toks) and toks[i] == ("op", "("):
            depth = 0
            while i < len(toks):
                if toks[i] == ("op", "("):
                    depth += 1
                elif toks[i] == ("op", ")"):
                    depth -= 1
                    if depth == 0:
                        i += 1
                        break
                i += 1
            else:
                return 0
        if i < len(toks) and toks[i] == ("op", "%"):
            i += 1
            continue
        return i


def balanced_close(toks, i):
    """Index of the token closing toks[i] == '(', or -1."""
    depth = 0
    for j in range(i, len(toks)):
        if toks[j] == ("op", "("):
            depth += 1
        elif toks[j] == ("op", ")"):
            depth -= 1
            if depth == 0:
                return j
    return -1


def expression_list_ok(toks):
    """A comma-separated list of expressions (keyword arguments allowed)."""
    if not toks:
        return True
    if toks[-1] == ("op", "&"):
        toks = toks[:-1]
    items, depth, cur = [], 0, []
    for t in toks:
        if t == ("op", "("):
            depth += 1
        elif t == ("op", ")"):
            depth -= 1
        if t == ("op", ",") and depth == 0:
            items.append(cur)
            cur = []
        else:
            cur.append(t)
    items.append(cur)
    for it in items:
        if len(it) >= 2 and it[0][0] == "name" and it[1] == ("op", "="):
            it = it[2:]
        if it == [("op", "*")] or (len(it) == 1 and it[0][0] in ("num", "str", "name")):
            continue
        if not expression_ok(it, fragment=depth != 0):
            return False
    return True


