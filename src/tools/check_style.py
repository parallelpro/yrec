def split_line(line, quote):
    """(code with literal contents blanked, comment text or None, quote
    state for the next line) of one physical line. `quote` is the quote
    of a literal continued from the previous line, or None."""
    code = []
    for i, ch in enumerate(line):
        if quote:
            code.append(ch if ch == quote else " ")
            if ch == quote:
                quote = None
        elif ch in "'\"":
            quote = ch
            code.append(ch)
        elif ch == "!":
            return "".join(code), line[i + 1:], None
        else:
            code.append(ch)
    text = "".join(code)
    if quote and not text.rstrip().endswith("&"):
        quote = None
    return text, None, quote


class Source:
    """One file read: its lines' code and comments, and its statements."""

    def __init__(self, text):
        self.lines = text.splitlines()
        self.code = []        # per line: masked code ("" for none)
        self.comment = []     # per line: comment text or None
        self.full_comment = []
        quote = None
        for line in self.lines:
            if line.lstrip().startswith("#"):
                self.code.append("")
                self.comment.append(None)
                self.full_comment.append(False)
                continue
            code, comment, quote = split_line(line, quote)
            self.code.append(code)
            self.comment.append(comment)
            self.full_comment.append(comment is not None and not code.strip())
        self.statements = list(self._statements())

    def _statements(self):
        """(line number from 1, statement text) for every statement."""
        buf, start = "", None
        for i, code in enumerate(self.code, 1):
            s = code.strip()
            if not s:
                continue
            if buf:
                s = s[1:] if s.startswith("&") else s
                buf += " " + s
            else:
                buf, start = s, i
            if buf.rstrip().endswith("&"):
                buf = buf.rstrip()[:-1]
                continue
            for part in buf.split(";"):
                part = re.sub(r"^\s*\d+\s+", "", part).strip()
                if part:
                    yield start, part
            buf = ""
        if buf.strip():
            yield start, buf.strip()


def matching_paren(text, i):
    """Index of the parenthesis closing text[i] == '(', or -1."""
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "(":
            depth += 1
        elif text[j] == ")":
            depth -= 1
            if depth == 0:
                return j
    return -1


def split_top(text, sep=","):
    """text split at `sep` outside parentheses."""
    parts, depth, cur = [], 0, []
    for ch in text:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == sep and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
    parts.append("".join(cur))
    return parts


