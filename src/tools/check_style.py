def statement_ok(text, toks=None):
    """Does text read as one Fortran statement (commented_code)?"""
    if toks is not None:
        text = " ".join(t[1] for t in toks)
    text = text.strip()
    if SIMPLE_STATEMENTS.match(text):
        return True
    toks = tokens(text) if toks is None else toks
    if not toks:
        return False
    if toks[0][0] == "num" and re.fullmatch(r"\d+", toks[0][1]):
        toks = toks[1:]
        if not toks:
            return False
    head = toks[0][1].lower() if toks[0][0] == "name" else None
    if head == "call" and len(toks) >= 2 and toks[1][0] == "name":
        rest = toks[2:]
        if not rest or rest == [("op", "&")]:
            return True
        if rest[0] == ("op", "(") and not rest[0].space:
            close = balanced_close(rest, 0)
            if close < 0:
                return rest[-1] == ("op", "&") and expression_list_ok(rest[1:])
            return close == len(rest) - 1 and expression_list_ok(rest[1:close]) \
                or rest[close + 1:] == [("op", "&")]
        return False
    if head in ("if", "elseif") or (head == "else" and len(toks) > 1 and toks[1][1].lower() == "if"):
        k = 1 if head != "else" else 2
        if k >= len(toks) or toks[k] != ("op", "("):
            return False
        close = balanced_close(toks, k)
        if close < 0 or not expression_ok(toks[k + 1:close]):
            return False
        rest = toks[close + 1:]
        if rest and rest[0][0] == "name" and rest[0][1].lower() == "then" and len(rest) == 1:
            return True
        return head == "if" and bool(rest) and statement_ok("", rest)
    if head == "do" and len(toks) > 1:
        if toks[1][0] == "name" and toks[1][1].lower() == "while":
            return len(toks) > 2 and toks[2] == ("op", "(") and balanced_close(toks, 2) == len(toks) - 1
        rest = toks[1:]
        if rest and rest[0][0] == "num":
            rest = rest[1:]
        if len(rest) >= 3 and rest[0][0] == "name" and rest[1] == ("op", "="):
            parts = [[]]
            depth = 0
            for t in rest[2:]:
                depth += t == ("op", "(")
                depth -= t == ("op", ")")
                if t == ("op", ",") and depth == 0:
                    parts.append([])
                else:
                    parts[-1].append(t)
            return len(parts) in (2, 3) and all(expression_ok(p) for p in parts)
        return False
    if head in ("write", "read", "open", "close", "inquire") and len(toks) > 1 and toks[1] == ("op", "("):
        close = balanced_close(toks, 1)
        if close < 0:
            return False
        return head in ("write", "read") and expression_list_ok(toks[close + 1:]) \
            or close == len(toks) - 1
    if head == "print" and len(toks) > 2 and toks[2] == ("op", ","):
        return toks[1] in (("op", "*"),) or toks[1][0] in ("num", "str") and expression_list_ok(toks[3:])
    if head == "format" and len(toks) > 1 and toks[1] == ("op", "("):
        return balanced_close(toks, 1) == len(toks) - 1
    if head == "use" and len(toks) >= 2 and toks[1][0] == "name":
        return len(toks) == 2 or (toks[2] == ("op", ",") and len(toks) > 3)
    if head == "stop" and len(toks) == 2 and toks[1][0] in ("str", "num"):
        return True
    if head and TYPE_SPEC.match(text) and any(t == ("op", ":") for t in toks) and "::" in text:
        return True
    n = designator_end(toks)
    if n and n < len(toks) and toks[n] == ("op", "="):
        rhs = toks[n + 1:]
        if rhs and rhs[-1][0] == "op" and rhs[-1][1] in BINARY_OPS:
            rhs = rhs + [Tok(("op", "&"))]   # a fixed-form statement continued
        return expression_ok(rhs)
    return False


def opens_continuation(body):
    """Does a code comment line continue on the next (`&`, or a fixed-form
    line ending in an operator)?"""
    toks = tokens(body)
    return bool(toks) and toks[-1][0] == "op" and (toks[-1][1] == "&" or toks[-1][1] in BINARY_OPS)


def commented_code_lines(src):
    """Line numbers (from 1) of the full-line comments that read as code."""
    hits, prev_open = [], False
    for i, (full, text) in enumerate(zip(src.full_comment, src.comment), 1):
        if not full:
            prev_open = False
            continue
        body = text.lstrip("!").strip()
        code_part, own_comment, _ = split_line(body, None)
        body = body[:len(code_part)].strip() if own_comment is not None else body
        if not body:
            prev_open = False
            continue
        is_code = statement_ok(body)
        if not is_code and prev_open:
            # a continuation line, after its marker (`&`, or fixed form's
            # `*`, `$`, `+` in column 6)
            toks = tokens(body[1:] if body[0] in "&*$+" else body)
            is_code = bool(toks) and expression_ok(toks, fragment=True)
        if is_code:
            hits.append(i)
        prev_open = is_code and opens_continuation(body)
    return hits


