IO_KEYWORD = re.compile(r"(?i)^(write|read|print|open|close|inquire|rewind|backspace|endfile|"
                        r"flush|wait)\b\s*(.*)$")


def peel_logical_if(stmt):
    """The statement a logical `if (...) stmt` guards, or stmt itself."""
    while True:
        m = re.match(r"(?i)^if\s*\(", stmt)
        if not m:
            return stmt
        close = matching_paren(stmt, m.end() - 1)
        if close < 0:
            return stmt
        rest = stmt[close + 1:].strip()
        if not rest or re.match(r"(?i)^then\b", rest):
            return stmt
        stmt = rest


def character_names(src):
    """Names declared `character` in a file: (every scope, module level
    and type components)."""
    every, shared = set(), set()

    def visit(stack, line, stmt):
        d = declaration(stmt)
        if d and d[0] == "character":
            names = {n for n, _ in d[2]}
            every.update(names)
            if stack and stack[-1].kind in ("module", "type"):
                shared.update(names)

    walk_scopes(src, visit)
    return every, shared


def transfer_unit(rest):
    """The unit of a write/read control list `( ... )` (text after the
    keyword), or None for the forms without one (`read *, x`)."""
    rest = rest.strip()
    if not rest.startswith("("):
        return None
    close = matching_paren(rest, 0)
    inner = rest[1:close] if close > 0 else rest[1:]
    items = split_top(inner)
    unit = items[0]
    for it in items:
        mm = re.match(r"(?i)\s*unit\s*=\s*(.*)$", it)
        if mm:
            unit = mm.group(1)
    return unit.strip()


def is_internal(unit, local_chars, shared_chars):
    if unit is None or unit == "*" or re.match(r"\d", unit):
        return False
    base = re.sub(r"\([^()]*\)", "", unit)
    name = base.split("%")[-1].strip().lower()
    if "%" in base:
        return name in shared_chars
    return name in local_chars or name in shared_chars


def io_statements(src, shared_chars, local_chars=None):
    """[(line, statement)] of the I/O statements of a file (internal
    writes and reads left out)."""
    if local_chars is None:
        local_chars = character_names(src)[0]
    out = []
    for line, stmt in src.statements:
        s = peel_logical_if(stmt)
        m = IO_KEYWORD.match(s)
        if not m:
            continue
        kw, rest = m.group(1).lower(), m.group(2)
        if kw in ("write", "read"):
            if not rest.startswith("(") and not (kw == "read" and re.match(r"[*\d']", rest)):
                continue
            if is_internal(transfer_unit(rest), local_chars, shared_chars):
                continue
        elif kw == "print":
            if not re.match(r"[*\d'\"]", rest):
                continue
        elif not re.match(r"\(|\w", rest):
            continue
        out.append((line, stmt))
    return out


