TYPE_SPEC = re.compile(r"(?i)^((?:double\s*precision|real|integer|logical|character|complex)\b|"
                       r"type\s*(?=\()|class\s*(?=\())")
PROC_PREFIX = r"(?:(?:pure|impure|elemental|recursive|non_recursive|module)\s+)"
PROC_HEADER = re.compile(
    r"(?i)^" + PROC_PREFIX + r"*"
    r"(?:(?:double\s*precision|real|integer|logical|character|complex|type|class)\s*"
    r"(?:\*\s*\d+\s*)?(?:\([^()]*(?:\([^()]*\)[^()]*)*\))?\s*)?" + PROC_PREFIX + r"*"
    r"(subroutine|function)\s+(\w+)\s*(\(([^()]*)\))?")
MODULE_START = re.compile(r"(?i)^module\s+(?!procedure\b|subroutine\b|function\b|"
                          r"pure\b|elemental\b|recursive\b|impure\b)(\w+)\s*$")
END_STMT = re.compile(r"(?i)^end\s*(subroutine|function|module|submodule|program|interface|"
                      r"type|block\s*data)?\b\s*(\w+)?\s*$")
OTHER_END = re.compile(r"(?i)^end\s*(if|do|select|where|forall|associate|block|critical|enum|"
                       r"team)\b")


def type_spec_end(stmt):
    """Index just past a declaration's type spec (kind selector or *len
    included), or -1 if the statement does not start with one."""
    m = TYPE_SPEC.match(stmt)
    if not m:
        return -1
    j = m.end()
    rest = stmt[j:]
    k = len(rest) - len(rest.lstrip())
    if rest[k:k + 1] == "(":
        close = matching_paren(stmt, j + k)
        if close < 0:
            return -1
        j = close + 1
    else:
        mm = re.match(r"\s*\*\s*(\d+|\(\s*\*\s*\))", stmt[j:])
        if mm:
            j += mm.end()
    return j


def declaration(stmt):
    """(type word, attributes, [(name, array spec or None)]) of a type
    declaration statement, or None."""
    j = type_spec_end(stmt)
    if j < 0:
        return None
    word = TYPE_SPEC.match(stmt).group(1).lower().replace(" ", "")
    rest = stmt[j:]
    if re.match(r"(?i)\s*(?:\w+\s+)*(function|subroutine)\b", rest):
        return None
    if "::" in rest:
        attrs, ents = rest.split("::", 1)
    else:
        if re.match(r"\s*,", rest) or not re.match(r"\s+[a-z_]", rest, re.I):
            return None
        attrs, ents = "", rest
    dim = None
    for a in split_top(attrs):
        mm = re.match(r"(?i)\s*dimension\s*\((.*)\)\s*$", a)
        if mm:
            dim = mm.group(1)
    entities = []
    for e in split_top(ents):
        e = split_top(e, "=")[0].strip()
        mm = re.match(r"(?i)([a-z_]\w*)\s*(\*\s*(?:\d+|\(\s*\*\s*\)))?\s*(\((.*)\))?", e)
        if mm:
            spec = mm.group(4) if mm.group(3) else dim
            entities.append((mm.group(1).lower(), spec))
    return word, attrs.lower(), entities


def assumed_shape(spec):
    return all(re.fullmatch(r"\s*[^:*]*:\s*", d) for d in split_top(spec))


class Scope:
    def __init__(self, kind, name, line, dummies=()):
        self.kind, self.name, self.line = kind, name, line
        self.dummies = {d.lower() for d in dummies}
        self.seen = set()
        self.private = False
        self.contains = False


def walk_scopes(src, on_statement):
    """Call on_statement(scope stack, line, statement) for each statement,
    and return [(module name, line, has bare private)]."""
    stack, modules = [], []

    def close(kinds):
        while stack:
            s = stack.pop()
            if s.kind == "module":
                modules.append((s.name, s.line, s.private))
            if s.kind in kinds:
                return

    for line, stmt in src.statements:
        low = stmt.lower()
        if OTHER_END.match(low):
            on_statement(stack, line, stmt)
            continue
        m = END_STMT.match(low)
        if m:
            what = (m.group(1) or "").replace(" ", "")
            if what in ("subroutine", "function"):
                close({"procedure"})
            elif what in ("module", "submodule", "program", "blockdata"):
                close({"module", "submodule", "program"})
            elif what in ("interface", "type"):
                close({what})
            elif stack:
                close({stack[-1].kind})
            continue
        m = MODULE_START.match(stmt)
        if m:
            stack.append(Scope("module", m.group(1), line))
            continue
        if re.match(r"(?i)^submodule\s*\(", stmt):
            stack.append(Scope("submodule", "", line))
            continue
        if re.match(r"(?i)^program\s+\w+", stmt):
            stack.append(Scope("program", "", line))
            continue
        if re.match(r"(?i)^(abstract\s+)?interface\b", stmt):
            stack.append(Scope("interface", "", line))
            continue
        if re.match(r"(?i)^type\s*(,[^:]*)?::\s*\w+\s*$|^type\s+(?!is\b)\w+\s*$", stmt):
            stack.append(Scope("type", "", line))
            continue
        m = PROC_HEADER.match(stmt)
        if m and not re.match(r"(?i)^module\s+procedure\b", stmt):
            args = [a.strip() for a in (m.group(4) or "").split(",") if a.strip()]
            stack.append(Scope("procedure", m.group(2), line, args))
            continue
        if re.match(r"(?i)^contains\s*$", stmt) and stack:
            stack[-1].contains = True
            continue
        if re.match(r"(?i)^private\s*$", stmt) and stack and stack[-1].kind == "module" \
                and not stack[-1].contains:
            stack[-1].private = True
        on_statement(stack, line, stmt)
    close(set())
    return modules


